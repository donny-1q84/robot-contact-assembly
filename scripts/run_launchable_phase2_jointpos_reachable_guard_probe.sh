set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

export RCA_LAUNCHABLE_JOINTPOS_PROBE_LABEL="${RCA_LAUNCHABLE_JOINTPOS_PROBE_LABEL:-jointpos-reachable-jointlimit-guard-probe}"
export RCA_LAUNCHABLE_REACHABLE_APPROACH="${RCA_LAUNCHABLE_REACHABLE_APPROACH:-1}"
export RCA_LAUNCHABLE_REACHABLE_APPROACH_START_RADIUS="${RCA_LAUNCHABLE_REACHABLE_APPROACH_START_RADIUS:-0.060}"
export RCA_LAUNCHABLE_REACHABLE_APPROACH_MIN_RADIUS="${RCA_LAUNCHABLE_REACHABLE_APPROACH_MIN_RADIUS:-0.000}"
export RCA_LAUNCHABLE_REACHABLE_APPROACH_SHRINK_STEP="${RCA_LAUNCHABLE_REACHABLE_APPROACH_SHRINK_STEP:-0.002}"
export RCA_LAUNCHABLE_REACHABLE_APPROACH_SHRINK_XY_TOL="${RCA_LAUNCHABLE_REACHABLE_APPROACH_SHRINK_XY_TOL:-0.015}"
export RCA_LAUNCHABLE_REACHABLE_APPROACH_JOINT_MARGIN_MIN="${RCA_LAUNCHABLE_REACHABLE_APPROACH_JOINT_MARGIN_MIN:-0.080}"

export RCA_LAUNCHABLE_SCRIPTED_STEPS="${RCA_LAUNCHABLE_SCRIPTED_STEPS:-1600}"
export RCA_LAUNCHABLE_TIMEOUT_SECONDS="${RCA_LAUNCHABLE_TIMEOUT_SECONDS:-2400}"
export RCA_LAUNCHABLE_FAIL_CLOSED_EXIT_ZERO="${RCA_LAUNCHABLE_FAIL_CLOSED_EXIT_ZERO:-1}"
