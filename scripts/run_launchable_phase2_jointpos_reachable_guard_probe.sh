export RCA_LAUNCHABLE_JOINT_LIMIT_NULLSPACE_STEP="${RCA_LAUNCHABLE_JOINT_LIMIT_NULLSPACE_STEP:-0.050}"
export RCA_LAUNCHABLE_JOINT_LIMIT_NULLSPACE_DAMPING="${RCA_LAUNCHABLE_JOINT_LIMIT_NULLSPACE_DAMPING:-0.075}"
export RCA_LAUNCHABLE_JOINT_LIMIT_GUARD_GAIN="${RCA_LAUNCHABLE_JOINT_LIMIT_GUARD_GAIN:-0.120}"
export RCA_LAUNCHABLE_JOINT_LIMIT_GUARD_ACTIVATION_MARGIN="${RCA_LAUNCHABLE_JOINT_LIMIT_GUARD_ACTIVATION_MARGIN:-0.180}"
export RCA_LAUNCHABLE_JOINT_LIMIT_GUARD_STEP="${RCA_LAUNCHABLE_JOINT_LIMIT_GUARD_STEP:-0.070}"

exec "${SCRIPT_DIR}/run_launchable_phase2_jointpos_nullspace_probe.sh" "$@"
