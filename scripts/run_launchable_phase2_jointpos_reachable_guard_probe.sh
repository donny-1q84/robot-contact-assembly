export RCA_LAUNCHABLE_JOINT_STEP_LIMIT_MODE="${RCA_LAUNCHABLE_JOINT_STEP_LIMIT_MODE:-after-xy-global}"

# Preserve early reach freedom, then keep late insertion away from the joint4 lower-limit branch.
export RCA_LAUNCHABLE_JOINT_LIMIT_MARGIN="${RCA_LAUNCHABLE_JOINT_LIMIT_MARGIN:-0.020}"
export RCA_LAUNCHABLE_INSERT_JOINT_LIMIT_MARGIN="${RCA_LAUNCHABLE_INSERT_JOINT_LIMIT_MARGIN:-0.120}"

# The projected term should start before joint4 becomes critical; the hard guard is a late fallback.
